export function getRoleLibraryFile(roleId: string): string {
  // Role ids are slugs generated by the roles route; reject anything that could leave the folder.
  if (!roleId || roleId !== path.basename(roleId)) {
    throw new Error(`Invalid role id "${roleId}"`);
  }

  ensureDir(LIBRARIES_DIR);
  return path.join(LIBRARIES_DIR, roleId);
}

export function getRoles(): Role[] {
  try {
    if (fs.existsSync(ROLES_FILE)) {
      const parsed = JSON.parse(fs.readFileSync(ROLES_FILE, 'utf-8'));
      if (Array.isArray(parsed)) return parsed as Role[];
    }
  } catch (error) {
    console.error('Error reading roles.json:', error);
  }

  return [];
}

export function saveRoles(roles: Role[]): void {
  ensureDir(DB_DIR);
  fs.writeFileSync(ROLES_FILE, JSON.stringify(roles, null, 2));
}

/**
 * First sync on a fresh install (roles.json missing): create the default roles and their library
 * files. "standard" gets every library Jellyfin currently reports; the others start empty. No-op
 * once roles.json exists.
 */
export function ensureDefaultRoles(libraries: Array<{ id: string; name: string }>): void {
  if (fs.existsSync(ROLES_FILE)) return;

  const defaults: Role[] = [
    { id: 'standard', name: 'Standard', maxParentalRating: null },
    { id: 'children', name: 'Children', maxParentalRating: 13 }
  ];

  saveRoles(defaults);

  for (const role of defaults) {
    const file = getRoleLibraryFile(role.id);
    if (fs.existsSync(file)) continue;

    const lines =
      role.id === 'standard' ? libraries.map((lib) => `${lib.id}->${lib.name}`).join('\n') : '';
    fs.writeFileSync(file, lines ? lines + '\n' : '');
  }

  if (!fs.existsSync(EXCLUDED_LIBRARIES_PATH)) fs.writeFileSync(EXCLUDED_LIBRARIES_PATH, '');
}

function readLibraryIds(filePath: string): string[] {
  if (!fs.existsSync(filePath)) return [];

  return fs
    .readFileSync(filePath, 'utf-8')
    .split('\n')
    .map((line) => line.split('->')[0].trim())
    .filter((id) => id !== '');
}

/**
 * Library ids listed in a library file. If an "admin" role exists, its libraries are left out,
 * matching how upstream's earlier version kept admin-only libraries away from regular roles.
 */
export function getLibraries(librariesPath: string): string[] {
  const adminIds = readLibraryIds(path.join(LIBRARIES_DIR, 'admin'));
  return readLibraryIds(librariesPath).filter((id) => !adminIds.includes(id));
}

function getBlockedTags(): string[] {
  if (!fs.existsSync(BLOCKED_TAGS_FILE)) return ['mature'];

  return fs
    .readFileSync(BLOCKED_TAGS_FILE, 'utf-8')
    .split('\n')
    .map((tag) => tag.trim())
    .filter((tag) => tag !== '');
}

/** Jellyfin user policy applied when a user is created with this role. */
export function getRolePolicy(role: Role) {
  const hasRatingCap = role.maxParentalRating !== null && role.maxParentalRating !== undefined;

  return {
    ...basePolicies,
    IsDisabled: false,
    MaxActiveSessions: 2,
    SyncPlayAccess: 'None',
    EnableContentDownloading: false,
    BlockedTags: hasRatingCap ? getBlockedTags() : [],
    EnabledFolders: getLibraries(getRoleLibraryFile(role.id)),
    ...(hasRatingCap ? { MaxParentalRating: role.maxParentalRating as number } : {})
  };
}

