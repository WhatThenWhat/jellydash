import fs from 'fs';
import path from 'path';

/**
 * Roles ("Access Groups" in the UI) and their library files.
 *
 * This file is a reconstruction. Upstream never committed the current version of it (the whole
 * app/db folder is gitignored), so it was rebuilt from how the rest of the code calls it, plus the
 * base policy values from the last version that was tracked in upstream history (commit
 * 442880d^). Review the defaults in ensureDefaultRoles and getRolePolicy against your needs.
 *
 * On-disk layout (all under app/db, all gitignored):
 *   roles.json           [{ id, name, maxParentalRating }]
 *   libraries/<role id>  one `libraryId->libraryName` line per library
 *   libraries/excluded   same format, libraries hidden from the home screen order
 *   ordered-views        JSON array of { id, name }
 *   blocked-tags         optional, one tag per line, applied to roles that have a rating cap
 */

export type Role = {
  id: string;
  name: string;
  maxParentalRating: number | null;
};

export type OrderedView = { id: string; name: string };

const DB_DIR = path.join(process.cwd(), 'app', 'db');
const LIBRARIES_DIR = path.join(DB_DIR, 'libraries');
const ROLES_FILE = path.join(DB_DIR, 'roles.json');
const ORDERED_VIEWS_FILE = path.join(DB_DIR, 'ordered-views');
const BLOCKED_TAGS_FILE = path.join(DB_DIR, 'blocked-tags');

export const EXCLUDED_LIBRARIES_PATH = path.join(LIBRARIES_DIR, 'excluded');

function ensureDir(dir: string) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

try {
  ensureDir(LIBRARIES_DIR);
} catch {
  // Read-only filesystem during a build step - directories get created on first write instead.
}

